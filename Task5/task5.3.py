def solve_5_3(year):
  if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    return "так"
  else:
    return "ні"


# Тести:
print(solve_5_3(2024))  # Очікується: так (кратний 4, але не 100)
print(solve_5_3(1900))  # Очікується: ні (кратний 100, але не 400)
print(solve_5_3(2000))  # Очікується: так (кратний 400)
print(solve_5_3(2023))  # Очікується: ні (звичайний рік)