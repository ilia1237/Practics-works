def solve_5_5(a, b, c):
  # Перевірка на додатні довжини та нерівність трикутника
  if (
      a <= 0
      or b <= 0
      or c <= 0
      or not (a + b > c and a + c > b and b + c > a)
  ):
    return "не трикутник"
  elif a == b == c:
    return "рівносторонній"
  elif a == b or b == c or a == c:
    return "рівнобедрений"
  else:
    return "різносторонній"


# Тести:
print(solve_5_5(3, 4, 5))  # Очікується: різносторонній
print(solve_5_5(2, 2, 2))  # Очікується: рівносторонній
print(solve_5_5(1, 2, 10))  # Очікується: не трикутник (порушення нерівності)
print(solve_5_5(5, 5, 8))  # Очікується: рівнобедрений