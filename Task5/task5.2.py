def solve_5_2(n):
  if n > 0:
    return "додатне"
  elif n < 0:
    return "від'ємне"
  else:
    return "нуль"


# Тести:
print(solve_5_2(-7))  # Очікується: від'ємне
print(solve_5_2(0))  # Очікується: нуль (межовий випадок)
print(solve_5_2(12))  # Очікується: додатне
print(solve_5_2(-0.0))  # Очікується: нуль (для дійсних чисел)