a = list(map(int, input("Введіть список через пробіл: ").split()))

print(f"Початковий список: {a}")
print(f"ID початкового об'єкта: {id(a)}")

# Реверс на місці обіруч без створення нового списку
n = len(a)
for i in range(n // 2):
  a[i], a[n - 1 - i] = a[n - 1 - i], a[i]

print(f"Результат реверсу: {a}")
print(f"ID кінцевого об'єкта: {id(a)} (ідентичний, новий список не створено)")